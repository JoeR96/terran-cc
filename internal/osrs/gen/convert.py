"""Converts RuneLite's farming tables to Go.

Usage: python -I convert.py <out.go>

Downloads PatchImplementation, Produce and FarmingWorld (plus the varbit and
item id tables they refer to) from RuneLite at a pinned commit, and writes
farming_gen.go. RuneLite is BSD-2 licensed; its notice is copied into the
output.
"""
import re
import sys
import urllib.request

COMMIT = 'e336ac270345c6c48e0fa69a6432d7fa03c5eb76'
BASE = f'https://raw.githubusercontent.com/runelite/runelite/{COMMIT}/'
TT = 'runelite-client/src/main/java/net/runelite/client/plugins/timetracking/farming/'
GV = 'runelite-api/src/main/java/net/runelite/api/gameval/'


def fetch(path):
    req = urllib.request.Request(BASE + path, headers={'User-Agent': 'terran-cc-gen'})
    return urllib.request.urlopen(req, timeout=60).read().decode('utf-8')


def top_level_ints(src):
    """public static final int NAME = N; at class level (one tab), skipping nested classes."""
    return {m.group(1): int(m.group(2)) for m in re.finditer(r'^\tpublic static final int (\w+) = (\d+);', src, re.M)}


def strip_comments(src):
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    return re.sub(r'//[^\n]*', '', src)


def balanced(src, start):
    """Returns the text inside the parentheses that open at src[start]."""
    depth = 0
    for i in range(start, len(src)):
        if src[i] == '(':
            depth += 1
        elif src[i] == ')':
            depth -= 1
            if depth == 0:
                return src[start + 1:i]
    raise ValueError('unbalanced')


def split_args(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '({':
            depth += 1
        elif ch in ')}':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def go_expr(e):
    e = re.sub(r'Produce\.(\w+)\.getStages\(\)', r'produces[P\1].Stages', e)
    return e.strip()


def patches(src):
    src = strip_comments(src)
    impls = []
    for m in re.finditer(r'^\t(\w+)\(Tab\.(\w+), "([^"]*)", (true|false)\)\s*\{', src, re.M):
        impls.append((m.group(1), m.group(4) == 'true', m.end()))
    out = []
    for i, (name, health, start) in enumerate(impls):
        end = impls[i + 1][2] if i + 1 < len(impls) else len(src)
        body = src[start:end]
        cases = []
        for c in re.finditer(r'if \(([^{]*?)\)\s*\{\s*return new PatchState\(Produce\.(\w+), CropState\.(\w+), ([^;]*?)\);\s*\}', body):
            cond = re.sub(r'\s+', ' ', c.group(1).strip())
            cases.append((cond, c.group(2), c.group(3), go_expr(c.group(4))))
        if not cases:
            raise SystemExit(f'no cases for {name}')
        out.append((name, health, cases))
    return out


def produces(src, items):
    src = strip_comments(src)
    rows = []
    for m in re.finditer(r'^\t(\w+)\(("[^"]*"[^;\n]*)\)[,;]', src, re.M):
        args = split_args(m.group(2))
        name = args[0].strip('"')
        rest = args[1:]
        contract = -1
        if rest and re.fullmatch(r'-?\d+', rest[0]):
            contract = int(rest.pop(0))
        impl = ''
        if rest and rest[0].startswith('PatchImplementation.'):
            impl = rest.pop(0).split('.', 1)[1]
        item = items.get(rest.pop(0).split('.', 1)[1], 0)
        nums = [int(x) for x in rest]
        tick, stages = nums[0], nums[1]
        regrow, harvest = (nums[2], nums[3]) if len(nums) == 4 else (0, 1)
        rows.append((m.group(1), name, contract, impl, item, tick, stages, regrow, harvest))
    return rows


def world(src, varbits):
    src = strip_comments(src)
    regions = []
    for m in re.finditer(r'new FarmingRegion\(', src):
        args = split_args(balanced(src, m.end() - 1))
        name, rid = args[0].strip('"'), int(args[1])
        ps = []
        for a in args[3:]:
            pm = re.match(r'new FarmingPatch\((.*)\)$', a, re.S)
            if not pm:
                continue
            pa = split_args(pm.group(1))
            ps.append((pa[0].strip('"'), varbits[pa[1].split('.', 1)[1]], pa[2].split('.', 1)[1]))
        regions.append((name, rid, ps))
    return regions


def main(out):
    varbits = top_level_ints(fetch(GV + 'VarbitID.java'))
    items = top_level_ints(fetch(GV + 'ItemID.java'))
    imps = patches(fetch(TT + 'PatchImplementation.java'))
    prods = produces(fetch(TT + 'Produce.java'), items)
    regs = world(fetch(TT + 'FarmingWorld.java'), varbits)
    lic = fetch('LICENSE')
    w = []
    w.append('// Code generated by gen/convert.py from RuneLite ' + COMMIT[:12] + '. DO NOT EDIT.\n//')
    w.extend('// ' + l if l else '//' for l in lic.strip().splitlines())
    w.append('\npackage osrs\n')
    w.append('const (')
    for i, (n, *_r) in enumerate(prods):
        w.append(f'\tP{n}' + (' produce = iota' if i == 0 else ''))
    w.append(')\n')
    w.append('var produces = [...]produceInfo{')
    for n, name, contract, impl, item, tick, stages, regrow, harvest in prods:
        w.append(f'\tP{n}: {{Name: "{name}", Contract: {contract}, Impl: "{impl}", ItemID: {item}, Tickrate: {tick}, Stages: {stages}, Regrow: {regrow}, HarvestStages: {harvest}}},')
    w.append('}\n')
    w.append('var implementations = map[string]impl{')
    for name, health, _ in imps:
        w.append(f'\t"{name}": {{health: {str(health).lower()}, state: state{name}}},')
    w.append('}\n')
    for name, _, cases in imps:
        w.append(f'func state{name}(value int) *patchState {{')
        for cond, prod, crop, expr in cases:
            w.append(f'\tif {cond} {{\n\t\treturn &patchState{{P{prod}, crop{crop.title().replace("_", "")}, {expr}}}\n\t}}')
        w.append('\treturn nil\n}\n')
    w.append('var regions = []region{')
    for name, rid, ps in regs:
        inner = ', '.join(f'{{"{pn}", {vb}, "{im}"}}' for pn, vb, im in ps)
        w.append(f'\t{{"{name}", {rid}, []patch{{{inner}}}}},')
    w.append('}')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(w) + '\n')
    print(f'{len(prods)} produce, {len(imps)} patch types, {len(regs)} regions -> {out}')


if __name__ == '__main__':
    main(sys.argv[1])
